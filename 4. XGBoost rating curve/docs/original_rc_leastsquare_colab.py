# Inverse Rating Curve: predict Stage from Discharge
# H = H0 + c * Q^m

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy.optimize import minimize_scalar

# 1. Load data
csv_path = '/content/Merged_Output_Ssp245.csv'
df = pd.read_csv(csv_path, parse_dates=['Date'], index_col='Date')
df = df.dropna()

# 2. Train-test split
train_mask = df.index < '2021-01-01'
test_mask  = df.index >= '2021-01-01'

Q_train = df.loc[train_mask, 'Modeled'].values   # discharge
H_train = df.loc[train_mask, 'Observed'].values  # stage
Q_test  = df.loc[test_mask, 'Modeled'].values
H_test  = df.loc[test_mask, 'Observed'].values

# 3. Fit H = H0 + c * Q^m on TRAIN only
def sse_for_H0(H0):
    if H0 >= H_train.min():
        return 1e12
    x = np.log(Q_train)
    y = np.log(H_train - H0)
    m, log_c = np.polyfit(x, y, 1)
    return np.sum((y - (log_c + m * x)) ** 2)

res = minimize_scalar(sse_for_H0, bounds=(-10, H_train.min() - 1e-3), method='bounded')
H0 = res.x

x = np.log(Q_train)
y = np.log(H_train - H0)
m, log_c = np.polyfit(x, y, 1)
c = np.exp(log_c)

print(f"Fitted Rating Curve:  H = {H0:.4f} + {c:.4f} * Q^{m:.4f}")

# 4. Predict stage
def predict_stage(Q):
    return H0 + c * Q ** m

H_train_pred = predict_stage(Q_train)
H_test_pred  = predict_stage(Q_test)

# 5. Metrics
def metrics(obs, pred, label):
    rmse = np.sqrt(np.mean((obs - pred) ** 2))
    mae  = np.mean(np.abs(obs - pred))
    r2   = 1 - np.sum((obs - pred) ** 2) / np.sum((obs - obs.mean()) ** 2)
    print(f"{label:6s}  RMSE={rmse:.4f} m   MAE={mae:.4f} m   R²={r2:.4f}")

metrics(H_train, H_train_pred, "Train")
metrics(H_test,  H_test_pred,  "Test")

# 6. Plots
fig, axes = plt.subplots(1, 2, figsize=(14, 5))

Q_all = np.linspace(min(Q_train.min(), Q_test.min()),
                    max(Q_train.max(), Q_test.max()), 200)
axes[0].scatter(Q_train, H_train, s=12, alpha=0.4, label='Train obs')
axes[0].scatter(Q_test,  H_test,  s=12, alpha=0.4, color='orange', label='Test obs')
axes[0].plot(Q_all, predict_stage(Q_all), 'r-', lw=2,
             label=f'H = {H0:.2f} + {c:.3f}·Q^{m:.3f}')
axes[0].set_xlabel('Discharge Q (m³/s)')
axes[0].set_ylabel('Stage H (m)')
axes[0].set_title('Rating Curve (fit on train)')
axes[0].legend(); axes[0].grid(alpha=0.3)

test_dates = df.index[test_mask]
axes[1].plot(test_dates, H_test, label='Observed', lw=1)
axes[1].plot(test_dates, H_test_pred, label='Predicted', lw=1, alpha=0.8)
axes[1].set_xlabel('Date'); axes[1].set_ylabel('Stage (m)')
axes[1].set_title('Test Period: Observed vs Predicted Stage')
axes[1].legend(); axes[1].grid(alpha=0.3)

plt.tight_layout()
plt.show()

# 7. Save train and test CSVs
train_out = pd.DataFrame({
    'Date': df.index[train_mask],
    'Observed': H_train,
    'Raw_Modeled': Q_train,
    'Corrected_Modeled': H_train_pred
})

test_out = pd.DataFrame({
    'Date': df.index[test_mask],
    'Observed': H_test,
    'Raw_Modeled': Q_test,
    'Corrected_Modeled': H_test_pred
})

train_out.to_csv('/content/train_rating_curve.csv', index=False)
test_out.to_csv('/content/test_rating_curve.csv', index=False)

print(f"Saved train ({len(train_out)} rows) and test ({len(test_out)} rows) CSVs.")