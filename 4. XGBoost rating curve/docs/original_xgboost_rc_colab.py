# Stage prediction from Discharge using XGBoost
# Predicts H (Observed) from Q (Modeled)

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from xgboost import XGBRegressor

# 1. Load data
csv_path = '/content/CNRM-CM6-1.csv'
df = pd.read_csv(csv_path, parse_dates=['Date'], index_col='Date')
df = df.dropna()

# 2. Train-test split
train_mask = df.index < '2005-01-01'
test_mask  = df.index >= '2005-01-01'

X_train = df.loc[train_mask, ['Modeled']].values   # discharge as feature
y_train = df.loc[train_mask, 'Observed'].values    # stage as target
X_test  = df.loc[test_mask,  ['Modeled']].values
y_test  = df.loc[test_mask,  'Observed'].values

# 3. Fit XGBoost on TRAIN only
model = XGBRegressor(
    n_estimators=500,
    max_depth=2,
    learning_rate=0.05,
    subsample=0.9,
    colsample_bytree=1.0,
    random_state=42,
    early_stopping_rounds=20
)
model.fit(X_train, y_train, eval_set=[(X_test, y_test)], verbose=False)

# 4. Predict
y_train_pred = model.predict(X_train)
y_test_pred  = model.predict(X_test)

# 5. Metrics
def metrics(obs, pred, label):
    rmse = np.sqrt(np.mean((obs - pred) ** 2))
    mae  = np.mean(np.abs(obs - pred))
    r2   = 1 - np.sum((obs - pred) ** 2) / np.sum((obs - obs.mean()) ** 2)
    print(f"{label:6s}  RMSE={rmse:.4f} m   MAE={mae:.4f} m   R²={r2:.4f}")

metrics(y_train, y_train_pred, "Train")
metrics(y_test,  y_test_pred,  "Test")

# 6. Plots
fig, axes = plt.subplots(1, 2, figsize=(14, 5))

Q_all = np.linspace(df['Modeled'].min(), df['Modeled'].max(), 500).reshape(-1, 1)
H_curve = model.predict(Q_all)

axes[0].scatter(X_train, y_train, s=12, alpha=0.4, label='Train obs')
axes[0].scatter(X_test,  y_test,  s=12, alpha=0.4, color='orange', label='Test obs')
axes[0].plot(Q_all, H_curve, 'r-', lw=2, label='XGBoost fit')
axes[0].set_xlabel('Discharge Q (m³/s)')
axes[0].set_ylabel('Stage H (m)')
axes[0].set_title('XGBoost Rating Curve (fit on train)')
axes[0].legend(); axes[0].grid(alpha=0.3)

test_dates = df.index[test_mask]
axes[1].plot(test_dates, y_test, label='Observed', lw=1)
axes[1].plot(test_dates, y_test_pred, label='Predicted', lw=1, alpha=0.8)
axes[1].set_xlabel('Date'); axes[1].set_ylabel('Stage (m)')
axes[1].set_title('Test Period: Observed vs Predicted Stage')
axes[1].legend(); axes[1].grid(alpha=0.3)

plt.tight_layout()
plt.show()

# 7. Save train and test CSVs
train_out = pd.DataFrame({
    'Date': df.index[train_mask],
    'Observed': y_train,
    'Raw_Modeled': X_train.ravel(),
    'Corrected_Modeled': y_train_pred
})

test_out = pd.DataFrame({
    'Date': df.index[test_mask],
    'Observed': y_test,
    'Raw_Modeled': X_test.ravel(),
    'Corrected_Modeled': y_test_pred
})

train_out.to_csv('/content/train_xgboost.csv', index=False)
test_out.to_csv('/content/test_xgboost.csv', index=False)

print(f"Saved train ({len(train_out)} rows) and test ({len(test_out)} rows) CSVs.")

