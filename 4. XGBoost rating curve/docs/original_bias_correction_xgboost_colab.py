# Step 1: Imports
import pandas as pd
import numpy as np
from sklearn.model_selection import RandomizedSearchCV
from sklearn.metrics import mean_squared_error, mean_absolute_error, r2_score
from xgboost import XGBRegressor
import matplotlib.pyplot as plt
import os
import joblib

# Step 2: Load Data
csv_path = '/content/Merged_Output_Ssp245.csv'
df = pd.read_csv(csv_path, parse_dates=['Date'], index_col='Date')

df

# --- Fix datatypes first ---
df['Modeled'] = pd.to_numeric(df['Modeled'], errors='coerce')
df['Observed'] = pd.to_numeric(df['Observed'], errors='coerce')

# --- Step 3: Feature Engineering ---
df['Modeled_Lag1'] = df['Modeled'].shift(1)
df['DayOfYear'] = df.index.dayofyear
df['Bias'] = df['Observed'] - df['Modeled']

df = df.dropna()

plt.figure(figsize=(12, 5))
plt.plot(df.index, df['Observed'], label='Observed')
plt.plot(df.index, df['Modeled'], label='Modeled')

plt.xlabel('Date')
plt.ylabel('Value')
plt.title('Observed vs Modeled Time Series')
plt.legend()
plt.grid(True)

plt.tight_layout()
plt.show()

# Step 4: Features and Target
X = df[['Modeled', 'Modeled_Lag1', 'DayOfYear']]
y = df['Bias']

# Step 5: Train-Test Split
train_mask = df.index < '2021-01-01'
test_mask = df.index >= '2021-01-01'
X_train, X_test = X[train_mask], X[test_mask]
y_train, y_test = y[train_mask], y[test_mask]
forecast_test_raw = df.loc[test_mask, 'Modeled']
observed_test = df.loc[test_mask, 'Observed']

# Step 6: Define Parameter Grid for RandomizedSearchCV
param_dist = {
    'n_estimators': [100, 200, 300, 400],
    'learning_rate': [0.01, 0.05, 0.1, 0.2],
    'max_depth': [3, 4, 5, 6],
    'subsample': [0.6, 0.8, 1.0],
    'colsample_bytree': [0.6, 0.8, 1.0],
    'gamma': [0, 0.1, 0.2, 0.3]
}

xgb_model = XGBRegressor(random_state=42)

random_search = RandomizedSearchCV(
    estimator=xgb_model,
    param_distributions=param_dist,
    n_iter=30,
    scoring='neg_mean_squared_error',
    cv=3,
    verbose=1,
    random_state=42,
    n_jobs=-1
)

# Step 7: Fit the Random Search
random_search.fit(X_train, y_train)

# Best parameters
print("🔧 Best Parameters:", random_search.best_params_)

# Step 8: Use Best Model
best_model = random_search.best_estimator_

# Predict & Correct
bias_pred = best_model.predict(X_test)
forecast_corrected = forecast_test_raw + bias_pred

# Step 9: Plot
plt.figure(figsize=(14,6))
plt.plot(df.index[test_mask], forecast_test_raw, label='Raw Forecast', linestyle='--', color='orange')
plt.plot(df.index[test_mask], forecast_corrected, label='Corrected Forecast (Tuned XGB)', color='green')
plt.plot(df.index[test_mask], observed_test, label='Observed', color='black')
plt.title('Tuned XGBoost Bias Correction – Solar Radiation (2024)')
plt.xlabel('Date')
plt.ylabel('Surface Net Solar Radiation (kW/m²/day)') # plt.ylabel('Temperature (°C)') # plt.ylabel('Rainfall (mm)')
plt.legend()
plt.grid(True)
plt.tight_layout()
plt.show()

# Step 10: Evaluation
rmse_raw = np.sqrt(mean_squared_error(observed_test, forecast_test_raw))
rmse_corrected = np.sqrt(mean_squared_error(observed_test, forecast_corrected))

mae_raw = mean_absolute_error(observed_test, forecast_test_raw)
mae_corrected = mean_absolute_error(observed_test, forecast_corrected)

# R-SQUARE
r2_raw = r2_score(observed_test, forecast_test_raw)
r2_corrected = r2_score(observed_test, forecast_corrected)

# CORRELATION COEFFICIENT (R)
R_raw = np.corrcoef(observed_test, forecast_test_raw)[0, 1]
R_corrected = np.corrcoef(observed_test, forecast_corrected)[0, 1]

# PRINT RESULTS
print("\n🔹 RMSE - Raw Forecast: {:.2f}".format(rmse_raw))
print("🔹 RMSE - Corrected (Tuned XGBoost): {:.2f}".format(rmse_corrected))

print("🔹 MAE - Raw Forecast: {:.2f}".format(mae_raw))
print("🔹 MAE - Corrected (Tuned XGBoost): {:.2f}".format(mae_corrected))

print("🔹 R² - Raw Forecast: {:.3f}".format(r2_raw))
print("🔹 R² - Corrected (Tuned XGBoost): {:.3f}".format(r2_corrected))

print("🔹 R  - Raw Forecast: {:.3f}".format(R_raw))
print("🔹 R  - Corrected (Tuned XGBoost): {:.3f}".format(R_corrected))

