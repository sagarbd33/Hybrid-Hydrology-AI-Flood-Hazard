def read_forcing(rel_path: str, start=None, end=None) -> pd.DataFrame:
    df = pd.read_csv(DATA_DIR / rel_path, parse_dates=["Date"]).set_index("Date").sort_index()
    if start or end:
        df = df.loc[start:end]
    return df


def project_dir(scenario: str) -> Path:
    return PROJECTS_DIR / scenario


def hms_date(ts: pd.Timestamp) -> str:
    """'1 January 1986' (HEC-HMS file format, no leading zero)."""
    return f"{ts.day} {ts.strftime('%B %Y')}"


def nse(obs, sim):
    import numpy as np
    obs, sim = np.asarray(obs, float), np.asarray(sim, float)
    return 1 - np.sum((sim - obs) ** 2) / np.sum((obs - obs.mean()) ** 2)
