# Import libraries
import numpy as np
import pandas as pd
from sklearn.preprocessing import MinMaxScaler
from sklearn.model_selection import train_test_split
from sklearn.metrics import mean_squared_error
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Bidirectional, GRU, Dense, Dropout
from tensorflow.keras.regularizers import l2
from tensorflow.keras.callbacks import EarlyStopping
import matplotlib.pyplot as plt

# Load the data from the CSV file
file_path = "/content/CNRM-CM6-1.csv"  # Replace with the actual file path
df = pd.read_csv(file_path, parse_dates=['Date'], index_col='Date')

df

# Define the number of time steps (window size)
n_steps = 15

# Prepare the data
def prepare_multivariate_data(data, n_steps):
    X, y = [], []
    for i in range(len(data)-n_steps):
        end_ix = i + n_steps
        seq_x, seq_y = data.iloc[i:end_ix, :-1], data.iloc[end_ix-1, -1]
        X.append(seq_x.values)
        y.append(seq_y)
    return np.array(X), np.array(y)

# Prepare data and split into training and testing sets
X, y = prepare_multivariate_data(df, n_steps)

X.shape

y.shape

# Normalize the data using MinMaxScaler
scaler_X = MinMaxScaler()
scaler_y = MinMaxScaler()

X_scaled = scaler_X.fit_transform(X.reshape(-1, X.shape[-1])).reshape(X.shape)
y_scaled = scaler_y.fit_transform(y.reshape(y.shape[0], 1))

# Split the data into training and testing sets (70% training, 30% testing)
X_train, X_test, y_train, y_test = train_test_split(X_scaled, y_scaled, test_size=0.3, random_state=42)

X_train.shape

X_test.shape

# Define the LSTM model
model = Sequential()
# model.add(Bidirectional(GRU(256, return_sequences=False, activation='relu', input_shape=(n_steps, X.shape[-1]), kernel_regularizer=l2(0.01))))
model.add(GRU(256, activation='relu', input_shape=(n_steps, X.shape[-1]), kernel_regularizer=l2(0.01), return_sequences=True))
model.add(Dropout(0.2))
model.add(GRU(128, return_sequences=True))
model.add(Dropout(0.2))
model.add(GRU(16))
model.add(Dropout(0.2))
model.add(Dense(1, activation='swish'))

# Compile the model with Nadam optimizer
from keras.optimizers import Nadam
optimizer = Nadam(learning_rate=0.001)  # You can adjust the learning rate as needed
model.compile(optimizer=optimizer, loss='mean_squared_error')

# Build the model to display the summary
model.build(input_shape=(None, n_steps, X.shape[-1]))

# Display the model summary
model.summary()

# Define Early Stopping
early_stopping = EarlyStopping(monitor='val_loss', verbose=1, mode='min', patience=20, restore_best_weights=True, start_from_epoch=50) # 10*30; 20*50

# # Train the model
# model.fit(X_train, y_train, epochs=50, batch_size=24, verbose=1)

# Train the model with early stopping
history = model.fit(X_train, y_train, epochs=300, batch_size=24, verbose=1, validation_data=(X_test, y_test), callbacks=[early_stopping]) # 70; 150

# Make predictions on the train set
y_pred_1 = model.predict(X_train)

# Inverse transform the predictions and actual values
y_pred_2 = scaler_y.inverse_transform(y_pred_1)
y_actual_2 = scaler_y.inverse_transform(y_train)

# calculate RMSE and nse to see how well are predictions are doing while train
# Calculate RMSE
rmse = np.sqrt(np.mean(np.power((y_actual_2 - y_pred_2), 2)))

# Calculate Standard Deviation of observed data
std_dev = np.std(y_actual_2)

# Calculate RSR
rsr = rmse / std_dev

# Calculate NSE
nse = 1 - (np.sum(np.power((y_actual_2 - y_pred_2), 2)) / np.sum(np.power((y_actual_2 - y_actual_2.mean()), 2)))

# Calculate MAE
mae = np.mean(np.abs(y_actual_2 - y_pred_2))

from sklearn.metrics import mean_absolute_error, mean_squared_log_error

# Calculate RMSLE
rmsle = np.sqrt(mean_squared_log_error(y_actual_2, y_pred_2))

# Calculate PBIAS
pbias = 100 * np.sum(y_pred_2 - y_actual_2) / np.sum(y_actual_2)

print(f" NSE: {nse:.4f} RMSE: {rmse:.4f} MAE: {mae:.4f} RMSLE: {rmsle:.4f} PBIAS: {pbias:.4f} RSR: {rsr:.4f}")

# Make predictions on the test set
y_pred = model.predict(X_test)

